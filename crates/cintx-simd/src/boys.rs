    x.store_to_f64_slice(&mut arr[..V::LANES]);
    let mut r0_arr = [0.0; 8];
    let mut r1_arr = [0.0; 8];
    let mut w0_arr = [0.0; 8];
    let mut w1_arr = [0.0; 8];

