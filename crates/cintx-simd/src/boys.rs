/// Vectorized Rys roots & weights for SIMD vectors `V`.
#[inline]
pub fn rys_root1_simd<V: SimdFloat>(x: V) -> (V, V) {
    let mut arr = [0.0; 8];
    x.store_to_f64_slice(&mut arr[..V::LANES]);
    let mut r_arr = [0.0; 8];
    let mut w_arr = [0.0; 8];

    for i in 0..V::LANES {
        let (r, w) = rys_root1_scalar(arr[i]);
        r_arr[i] = r;
        w_arr[i] = w;
    }

    (
        V::from_f64_slice(&r_arr[..V::LANES], 0.0),
        V::from_f64_slice(&w_arr[..V::LANES], 0.0),
    )
}

/// Vectorized 2-root Rys roots & weights for SIMD vectors `V`.
